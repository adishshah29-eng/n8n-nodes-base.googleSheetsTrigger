// Voice-recording tooling. The scenario files are the single source of truth for what must be spoken.
//
//   node scripts/audio-manifest.js          writes content/audio/RECORDING_SCRIPT.md and .csv
//   node scripts/audio-manifest.js --check  lists clips not yet recorded, per language
//
// Every spoken line is a recorded clip from a native speaker: there is no text-to-speech anywhere.
// Clip files live at content/audio/<lang>/<key>.mp3 (mono, 48 kbps, under 12 s each).
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(fileURLToPath(import.meta.url), '../..');
const dir = join(root, 'content/scenarios');
const gestures = JSON.parse(readFileSync(join(root, 'content/gestures.json'), 'utf8'));
const scenarios = readdirSync(dir).filter((f) => f.endsWith('.json')).sort().map((f) => JSON.parse(readFileSync(join(dir, f), 'utf8')));

const LANGS = ['sat', 'hi', 'en'];
const LANG_NAMES = { sat: 'Santali', hi: 'Hindi', en: 'English' };

/** Every clip the app can ask for: { key, where, kind, en, hi }. */
export function clips() {
  const out = [
    // The language picker: each button is SPOKEN in its own language, so each language records its own name.
    ...LANGS.map((l) => ({ key: `lang_${l}`, where: 'Language picker', kind: 'Say the language name', en: LANG_NAMES[l], hi: { sat: 'संताली (ᱥᱟᱱᱛᱟᱲᱤ)', hi: 'हिन्दी', en: 'अंग्रेज़ी (English)' }[l], onlyIn: l })),
  ];
  for (const s of scenarios) {
    const title = s.title?.en ?? s.id;
    for (const step of s.steps) {
      const where = `${title} · step ${step.id}`;
      if (step.audio) out.push({ key: `${s.id}_${step.audio}`, where, kind: step.type === 'hazard' ? 'Situation' : 'Question / instruction', en: step.text?.en ?? '', hi: step.text?.hi ?? '' });
      if (step.type === 'choice') {
        for (const o of step.options) {
          out.push({ key: `${s.id}_${step.id}_opt_${o.id}`, where, kind: 'Option (heard on first tap)', en: o.label?.en ?? '', hi: o.label?.hi ?? '' });
          if (o.feedback) out.push({ key: `${s.id}_${o.feedback}`, where, kind: o.critical ? 'Feedback: CRITICAL mistake' : 'Feedback: wrong choice', en: o.feedbackText?.en ?? '', hi: o.feedbackText?.hi ?? '' });
        }
      }
      if (step.type === 'action') {
        for (const p of gestures[step.gesture] ?? []) {
          out.push({ key: `${s.id}_${step.id}_${p.id}`, where, kind: 'Action part (heard when done)', en: p.label.en, hi: p.label.hi });
        }
      }
    }
  }
  return out;
}

const csvCell = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
const mdCell = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

function write() {
  const all = clips();
  const perLang = (l) => all.filter((c) => !c.onlyIn || c.onlyIn === l);
  const lines = [
    '# Recording script',
    '',
    'Generated by `node scripts/audio-manifest.js` from `content/scenarios/*.json` — do not edit by hand.',
    '',
    '**How to record**',
    '1. Record each line in a quiet room on a phone: 3 takes per line, keep the best. One line = one file.',
    '2. Hindi is the source script. The Santali speaker translates it (spoken, simple, short) and records it.',
    '3. Trim silence, normalise loudness, export **MP3, mono, 48 kbps, under 12 seconds** (Audacity).',
    '4. Name the file exactly as in the **File** column and drop it in `content/audio/<lang>/` (`sat`, `hi`, `en`).',
    '5. Run `node scripts/audio-manifest.js --check` to see what is still missing.',
    '',
    `Clips per language: ${perLang('hi').length} (${perLang('hi').length - 1} scenario lines plus the language name). Total across 3 languages: ${LANGS.reduce((n, l) => n + perLang(l).length, 0)}.`,
    '',
    '| File (`<lang>/<name>.mp3`) | Where | What to say | English (reference) | Hindi (source) | Santali (translator fills in) |',
    '| --- | --- | --- | --- | --- | --- |',
    ...all.map((c) => `| \`${c.key}.mp3\` | ${mdCell(c.where)} | ${c.kind} | ${mdCell(c.en)} | ${mdCell(c.hi)} |  |`),
    '',
  ];
  writeFileSync(join(root, 'content/audio/RECORDING_SCRIPT.md'), lines.join('\n'));
  const csv = [['file', 'where', 'kind', 'english', 'hindi', 'santali'].join(','), ...all.map((c) => [`${c.key}.mp3`, c.where, c.kind, c.en, c.hi, ''].map(csvCell).join(','))];
  writeFileSync(join(root, 'content/audio/recording-script.csv'), csv.join('\n') + '\n');
  console.log(`wrote content/audio/RECORDING_SCRIPT.md and recording-script.csv (${all.length} distinct clip names)`);
}

function check() {
  const all = clips();
  let missingAny = false;
  for (const l of LANGS) {
    const need = all.filter((c) => !c.onlyIn || c.onlyIn === l);
    const missing = need.filter((c) => !existsSync(join(root, 'content/audio', l, `${c.key}.mp3`)));
    console.log(`${LANG_NAMES[l].padEnd(8)} ${need.length - missing.length}/${need.length} recorded`);
    if (missing.length && process.argv.includes('--list')) missing.forEach((c) => console.log(`   missing ${l}/${c.key}.mp3`));
    missingAny ||= missing.length > 0;
  }
  if (missingAny) console.log('(add --list to see every missing file; Santali falls back to Hindi clips when a clip is missing)');
}

if (process.argv.includes('--check')) check();
else write();
